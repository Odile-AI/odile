#!/usr/bin/python3
"""ODL-947 — a seeded first boot must open the gate with the registration password.

The order on a tenant is the machine's, not a fixture's:

1. ``odile-firstboot.py`` writes ``/etc/odile/first-visit.json`` *before* the
   installer runs.
2. the first boot's installer is ``deploy/image/install-stack.sh --seed``; its
   production branch writes the tenant ``.env``.
3. ``odile-release-setup.sh`` then runs the release installer, whose
   ``ensure_env`` converges the same file on every boot.

Release ``2026.11.23-5`` stamped ``signin_set_at`` in step 1, on the seed's
mere presence, before any writer had put the seed's verifier in the ``.env``.
``install-stack.sh`` trusted the stamp and kept the image's placeholder, the
installer kept it too, and the first-visit page served a login whose password
nobody knew (``docs/evidence/a2-cold-walk.md`` §2.6).

These tests drive that real order: the real ``odile-firstboot.py`` state
function, the real ``install-stack.sh`` production branch, the real
``installer.ensure_env``, and the shipped ``first_visit.py`` process. The
production branch is executed exactly as it ships — the test takes the block
between its first line and the line that follows it, and runs it with the four
paths a temp root needs — so a change to the branch is measured here, not
re-implemented.

    /usr/bin/python3 -m unittest discover -s tests -p 'test_first_visit_signin.py' -v
"""

from __future__ import annotations

import contextlib
import http.client
import importlib.util
import io
import json
import os
import pwd
import secrets
import shlex
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IMAGE = ROOT / "deploy" / "image"
INSTALL_STACK = IMAGE / "install-stack.sh"
FIRSTBOOT = IMAGE / "odile-firstboot.py"
INSTALLER = ROOT / "installer" / "odile_install.py"
SERVICE = ROOT / "installer" / "first_visit.py"
PAGE = ROOT / "web" / "first-visit.html"
#: The five files the page server answers and the installer pins (ODL-505).
ICON_FILES = ("favicon.ico", "icon-32.png", "icon-192.png", "icon-512.png",
              "apple-touch-icon.png")

#: The password chosen at registration: the account's scrypt verifier is what
#: the seed carries byte for byte as ``sign_in_hash``.
REG_PASSWORD = "reg-pass-947"
INSTANCE = "45445445-0000-4000-8000-000000000947"
TOKEN = "ab" * 32


def load_module(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def image_env(username: str, password_hash: str, secret: str) -> str:
    """The published image's .env: a scrypt hash of a discarded password."""
    return (
        "# Odile tenant .env — generated by deploy/image/install-stack.sh, never edited\n"
        "# by hand. Exactly three keys: the owner's sign-in and the session signing\n"
        "# secret. No provider key: the inference credential is in /etc/odile/key.env.\n"
        "# odile-signin-placeholder: 1\n"
        f"HERMES_DASHBOARD_BASIC_AUTH_USERNAME={username}\n"
        f"HERMES_DASHBOARD_BASIC_AUTH_PASSWORD_HASH={password_hash}\n"
        f"HERMES_DASHBOARD_BASIC_AUTH_SECRET={secret}\n"
    )


class SeededFirstBootTests(unittest.TestCase):
    """The order a registered machine takes, with the shipped programs."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.installer = load_module(INSTALLER, "odile_install_947")
        cls.firstboot = load_module(FIRSTBOOT, "odile_firstboot_947")

    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory(prefix="odl947-")
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.user = pwd.getpwuid(os.getuid()).pw_name
        self.layout = self.installer.Layout.scratch(
            root=self.root, user=self.user, webapp_port=9130,
            public_url="https://odl-947.odile.fyi")
        self.layout.hermes_home.mkdir(parents=True)
        self.layout.etc.mkdir(parents=True)
        self.state_path = self.layout.first_visit_state
        self.env_path = self.layout.hermes_home / ".env"
        # The as-built image's file: a scrypt hash of a discarded password, the
        # marker that says so, and this machine's session secret.
        self.image_hash = self.installer.hash_password(
            "discarded-" + secrets.token_hex(8))
        self.image_secret_placeholder = "0123456789abcdef" * 4
        self.write_image_env()
        self.seed = {
            "slug": "odl-947",
            "instance_id": INSTANCE,
            "near_api_key": "key-947",
            "model": "deepseek-ai/DeepSeek-V4.1-Flash-1017-abliterated",
            "support_public_key": "ssh-ed25519 AAAA odile placeholder",
            "backup_repo_url": "sftp://backup.invalid/srv/odl-947",
            "mail_relay": {"host": "relay.invalid", "port": 587,
                           "username": "relay", "secret": "relay-secret"},
            "hermes_version": "Hermes Agent v0.23.0",
            "sign_in_hash": self.installer.hash_password(REG_PASSWORD),
        }
        self.seed_path = self.root / "seed.json"
        self.seed_path.write_text(json.dumps(self.seed), encoding="utf-8")
        self.production_marker = self.root / "production"
        self.production_marker.write_text("the published image\n", encoding="utf-8")

    # -- fixtures --------------------------------------------------------

    def write_image_env(self) -> None:
        self.env_path.write_text(
            image_env(self.user, self.image_hash, self.image_secret_placeholder), encoding="utf-8")
        self.env_path.chmod(0o600)

    def write_pre_installer_state(self, stamped: bool = False) -> None:
        """The state firstboot writes before the installer runs.

        ``stamped`` reproduces the pre-fix order (release 2026.11.23-5), which
        set ``signin_set_at`` on the seed's mere presence; the fix leaves it
        null and lets the writer of the verifier stamp it.
        """
        state = json.loads(self.firstboot.first_visit_state(TOKEN))
        if stamped:
            state["signin_set_at"] = state["created_at"]
        self.state_path.parent.mkdir(parents=True, exist_ok=True)
        self.state_path.write_text(
            json.dumps(state, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        self.state_path.chmod(0o600)

    def production_branch(self) -> str:
        """install-stack.sh's .env block, verbatim, with its paths redirected.

        The block starts at the fixture-password hash line and ends where the
        script moves on to the tenant home directories; everything the block
        calls is defined inside it except the four variables and ``say``, which
        the harness supplies. The two absolute paths are pointed at this temp
        root so the run can never read or write the host's ``/etc/odile``.
        """
        source = INSTALL_STACK.read_text(encoding="utf-8")
        start = "password_sha=$(printf"
        end = 'install -d -o "$TENANT_USER" -g "$TENANT_USER" -m 0700 "$HERMES_HOME/scripts"'
        self.assertIn(start, source, "install-stack.sh's .env block moved")
        self.assertIn(end, source, "the line after install-stack.sh's .env block moved")
        block = source[source.index(start):source.index(end)]
        block = block.replace("/etc/odile/first-visit.json", "$STATE_FILE")
        block = block.replace("/etc/odile/production", "$PRODUCTION_MARKER")
        preamble = "\n".join([
            "#!/bin/bash",
            "set -euo pipefail",
            'say() { printf "%-12s %s\\n" "$1" "$2"; }',
            'TENANT_USER=%s' % shlex.quote(self.user),
            'HERMES_HOME=%s' % shlex.quote(str(self.layout.hermes_home)),
            'BENCH_PASSWORD=%s' % shlex.quote("odile-bench-not-a-secret"),
            'SEED_FILE=%s' % shlex.quote(str(self.seed_path)),
            'STATE_FILE=%s' % shlex.quote(str(self.state_path)),
            'PRODUCTION_MARKER=%s' % shlex.quote(str(self.production_marker)),
        ])
        return preamble + "\n" + block + "\n"

    def run_install_stack(self) -> str:
        """Run the production branch install-stack.sh carries, on this root."""
        path = self.root / "production-branch.sh"
        path.write_text(self.production_branch(), encoding="utf-8")
        result = subprocess.run(["bash", str(path)], capture_output=True,
                                text=True, timeout=180)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.branch_output = result.stdout
        return result.stdout

    def run_ensure_env(self) -> tuple[bool, str | None]:
        """The release installer's per-boot convergence of the same file."""
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            result = self.installer.ensure_env(
                self.layout, None, self.user, False, first_visit=True,
                sign_in_hash=self.seed["sign_in_hash"])
        self.env_output = output.getvalue()
        return result

    def stored_hash(self) -> str:
        return self.installer.env_values(
            self.env_path.read_text(encoding="utf-8")
        ).get("HERMES_DASHBOARD_BASIC_AUTH_PASSWORD_HASH", "")

    def stored_secret(self) -> str:
        return self.installer.env_values(
            self.env_path.read_text(encoding="utf-8")
        ).get("HERMES_DASHBOARD_BASIC_AUTH_SECRET", "")

    def load_state(self) -> dict:
        return json.loads(self.state_path.read_text(encoding="utf-8"))

    # -- the shipped page ------------------------------------------------

    def start_service(self) -> int:
        icons = self.root / "icons"
        icons.mkdir()
        for name in ICON_FILES:
            shutil.copyfile(ROOT / "web" / name, icons / name)
        port = free_port()
        process = subprocess.Popen(
            [sys.executable, str(SERVICE), "--bind", "127.0.0.1", "--port", str(port),
             "--state", str(self.state_path), "--env-file", str(self.env_path),
             "--page", str(PAGE), "--recovery-file", str(self.layout.recovery),
             "--icons", str(icons), "--reload-command", "", "--report-command", "",
             "--report-file", str(self.root / "report.txt"),
             "--attest-file", str(self.root / "attest.json")],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        self.addCleanup(self._stop, process)
        for _ in range(100):
            try:
                status, _ = self._call(port, "GET", "/health")
                if status == 200:
                    self.port = port
                    return port
            except OSError:
                pass
            time.sleep(0.05)
        raise AssertionError("the first-visit service did not start")

    @staticmethod
    def _stop(process: subprocess.Popen) -> None:
        if process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                process.kill()
        if process.stdout is not None:
            process.stdout.close()

    def _call(self, port: int, method: str, path: str,
              fields: dict[str, str] | None = None) -> tuple[int, str]:
        body = None
        headers = {}
        if fields is not None:
            body = "&".join("%s=%s" % item for item in fields.items()).encode()
            headers["Content-Type"] = "application/x-www-form-urlencoded"
        connection = http.client.HTTPConnection("127.0.0.1", port, timeout=20)
        try:
            connection.request(method, path, body=body, headers=headers)
            response = connection.getresponse()
            return response.status, response.read().decode("utf-8", "replace")
        finally:
            connection.close()

    def sign_in(self, password: str) -> tuple[int, str]:
        """The B-once login POST: one password, verified against the .env."""
        return self._call(self.port, "POST", "/first-visit", {"password": password})

    # -- the gate --------------------------------------------------------

    def test_the_base_pre_installer_stamp_no_longer_hides_the_seed_verifier(self) -> None:
        """The DoD's real order, starting from the pre-fix state.

        Release 2026.11.23-5 wrote ``signin_set_at`` before the installer ran.
        The writer of the verifier must not trust that stamp: it writes the
        seed's hash when the .env does not hold it, and only then is the stamp
        true. The page then accepts the password chosen at registration.
        """
        self.write_pre_installer_state(stamped=True)
        self.run_install_stack()
        self.assertEqual(
            self.stored_hash(), self.seed["sign_in_hash"],
            "install-stack kept the image's placeholder while the state already "
            "said the sign-in was set (the 2026.11.23-5 order)")
        self.run_ensure_env()
        self.assertEqual(self.stored_hash(), self.seed["sign_in_hash"],
                         "the release installer reverted the seed's verifier")
        state = self.load_state()
        self.assertIsNotNone(state["signin_set_at"])
        self.start_service()
        status, body = self.sign_in(REG_PASSWORD)
        self.assertEqual(status, 200)
        self.assertIn("You are signed in", body,
                      "the first visit is not a login with the registration password")

    def test_the_pre_installer_state_carries_no_stamp_and_the_writer_stamps_it(self) -> None:
        """The state is a fact about the .env: null here, stamped after the write."""
        state = json.loads(self.firstboot.first_visit_state(TOKEN))
        self.assertIsNone(state["signin_set_at"],
                          "the pre-installer state claims a sign-in no writer set")
        self.assertTrue(self.firstboot.write_first_visit_state(
            str(self.state_path), TOKEN))
        self.assertIsNone(self.load_state()["signin_set_at"])
        self.run_install_stack()
        self.assertEqual(self.stored_hash(), self.seed["sign_in_hash"])
        self.assertIsNotNone(
            self.load_state()["signin_set_at"],
            "the writer of the seed's verifier did not stamp the state")
        self.assertNotEqual(self.stored_secret(), self.image_secret_placeholder,
                            "the first boot kept the image's shared session secret")

    def test_a_second_boot_keeps_the_env_bytes_and_the_stamp(self) -> None:
        """After the seed's verifier is in place, every later run is a no-op."""
        self.write_pre_installer_state()
        self.run_install_stack()
        before = self.env_path.read_bytes()
        stamp = self.load_state()["signin_set_at"]
        self.assertIsNotNone(stamp)
        output = self.run_install_stack()
        self.assertIn("the seed's verifier; this machine's own secret", output)
        self.assertEqual(self.env_path.read_bytes(), before,
                         "a second first-boot run rewrote the .env")
        self.assertEqual(self.load_state()["signin_set_at"], stamp,
                         "a second run moved the stamp")
        self.run_ensure_env()
        self.assertEqual(self.env_path.read_bytes(), before,
                         "the release installer rewrote a converged .env")
        self.assertEqual(self.stored_hash(), self.seed["sign_in_hash"])
        self.assertEqual(self.load_state()["signin_set_at"], stamp)

    def test_the_release_installer_writes_the_seed_verifier_when_no_writer_has(self) -> None:
        """The installer is the third writer: it writes, then stamps.

        When the first-boot half left the placeholder (state unstamped, .env
        the image's hash) ``ensure_env`` writes the seed's verifier and then
        stamps the state, keeping the machine's session secret.
        """
        self.write_pre_installer_state()
        changed, _ = self.run_ensure_env()
        self.assertTrue(changed)
        self.assertEqual(self.stored_hash(), self.seed["sign_in_hash"])
        self.assertIsNotNone(self.load_state()["signin_set_at"],
                             "the installer wrote the verifier without stamping")
        self.assertEqual(self.stored_secret(), self.image_secret_placeholder,
                         "the installer rotated the machine's session secret")

    def test_a_page_converged_signin_is_not_reverted(self) -> None:
        """The owner's own sign-in (a page write or a reset) is kept.

        On a seeded machine the page's first visit is a login; a reset writes a
        new hash. The state then carries ``used_at``/``first_login_at`` and the
        hash is no longer the seed's, so neither writer may replace it.
        """
        self.write_pre_installer_state()
        self.run_install_stack()
        owner_hash = self.installer.hash_password("the-owner-new-password-0003")
        self.env_path.write_text(
            self.installer.render_env(self.user, owner_hash, self.stored_secret()),
            encoding="utf-8")
        self.env_path.chmod(0o600)
        state = self.load_state()
        at = "2026-11-24T09:00:00Z"
        state["used_at"] = state.get("used_at") or at
        state["first_login_at"] = at
        self.state_path.write_text(
            json.dumps(state, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        before = self.env_path.read_bytes()
        self.run_install_stack()
        self.assertEqual(self.env_path.read_bytes(), before,
                         "install-stack reverted the owner's own sign-in")
        self.run_ensure_env()
        self.assertEqual(self.env_path.read_bytes(), before,
                         "the release installer reverted the owner's own sign-in")
        self.assertEqual(self.stored_hash(), owner_hash)


if __name__ == "__main__":
    unittest.main()
