#!/usr/bin/python3
"""Build the off-box Odile factory recovery kit.

Run on HQ when a token rotates (or once, to refresh the fallback manifest):

    /usr/bin/python3 scripts/factory_recovery_kit.py --out ~/odile-factory-recovery

It reads the secrets HQ already holds, writes a five-file folder, and prints
where it is and how to store it. It never prints a secret. The produced folder
is the thing to put in 1Password and on a USB stick; if HQ is gone, the folder
plus a fresh VPS is all the recovery needs.

There is no "run this before the box dies" step for the *facts*: the nightly
backup writes the Hermes commit, the host IPv4, the zone id and the DNS names
into every snapshot's `manifest.json`, and `recover.sh` reads them from there.
The kit is the secrets plus the script; its own `manifest.json` is the fallback
for a snapshot taken before the backup wrote that block. Regenerate the kit
after an R2 or Cloudflare token rotation, or when the tagged zone changes.

Files: README.md, recovery.env (0600), recover.sh (0700), manifest.json,
CHECKSUMS.txt. The script and the one-page guide are the repository's
`deploy/recovery/` copies, so the kit is versioned with the code that reads it.

The recover script prefers the Hermes commit and DNS facts from the latest
backup snapshot's manifest; the kit's `manifest.json` is the fallback written at
generation. Regenerate after an R2 or Cloudflare token rotation, or when the
tagged zone changes.

    --out DIR       where to write the kit (default ~/odile-factory-recovery)
    --force         replace an existing folder
    --zone-id ID    the 32-hex Cloudflare zone id (default: the state file)
    --state-dir DIR where the secrets live (default /root/.odile; tests)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shlex
import shutil
import socket
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
RECOVERY_DIR = REPO_ROOT / "deploy" / "recovery"
README = RECOVERY_DIR / "README.md"
RECOVER = RECOVERY_DIR / "recover.sh"
DNS_NAMES_FILE = RECOVERY_DIR / "dns-names.txt"
DNS_SKIP_FILE = RECOVERY_DIR / "dns-skip.txt"
DEFAULT_STATE_DIR = Path("/root/.odile")
DEFAULT_OUT = Path.home() / "odile-factory-recovery"
BUCKET = "hermes-hq-backup"

# Fallbacks only; deploy/recovery/*.txt is the source.
DNS_NAMES = ("odile.fyi", "gw.odile.fyi", "mail.odile.fyi", "testing.odile.fyi",
             "test.odile.fyi")
DNS_SKIP = ("demo.odile.fyi", "www.odile.fyi", "odl-7971a8.odile.fyi",
            "odl-*.test.odile.fyi")
KIT_FILES = ("README.md", "recovery.env", "recover.sh", "manifest.json",
             "CHECKSUMS.txt")


def read_secret(path: Path, label: str) -> str:
    try:
        value = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise SystemExit(f"error: cannot read {label} at {path}: {exc.strerror}") from exc
    value = value.strip("\r\n")
    if not value:
        raise SystemExit(f"error: {label} at {path} is empty")
    return value


def read_r2(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise SystemExit(f"error: cannot read the R2 env at {path}: {exc.strerror}") from exc
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip("'\"")
    for key in ("AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY", "R2_ENDPOINT"):
        if not values.get(key):
            raise SystemExit(f"error: {key} is missing from {path}")
    return values


def read_names(path: Path, fallback: tuple[str, ...]) -> list[str]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return list(fallback)
    names = [line.strip() for line in lines
             if line.strip() and not line.lstrip().startswith("#")]
    return names or list(fallback)


def write_env(path: Path, values: dict[str, str]) -> None:
    lines = [
        "# Odile factory recovery — secrets. Store in 1Password and a USB.",
        "# Generated by scripts/factory_recovery_kit.py; do not commit.",
        "",
    ]
    for key in (
        "RESTIC_PASSWORD",
        "R2_ACCESS_KEY_ID",
        "R2_SECRET_ACCESS_KEY",
        "R2_ENDPOINT",
        "CLOUDFLARE_ACCOUNT_ID",
        "CLOUDFLARE_DNS_TOKEN",
        "ZONE_ID",
    ):
        lines.append(f"{key}={shlex.quote(values[key])}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    path.chmod(0o600)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def run(*args: str) -> str:
    try:
        return subprocess.run(
            args, capture_output=True, text=True, timeout=30, check=False
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


def detect_ipv4() -> str:
    route = run("ip", "-4", "route", "get", "1.1.1.1")
    match = re.search(r"\bsrc\s+(\d+\.\d+\.\d+\.\d+)", route)
    if match:
        return match.group(1)
    for token in run("hostname", "-I").split():
        if re.fullmatch(r"\d+\.\d+\.\d+\.\d+", token):
            return token
    return ""


def hermes_identity() -> tuple[str, str]:
    version = os.environ.get("ODILE_HERMES_VERSION", "")
    commit = os.environ.get("ODILE_HERMES_COMMIT", "")
    if not version:
        output = run("hermes", "--version")
        version = output.splitlines()[0] if output else ""
    if not commit:
        match = re.search(r"local\s+([0-9a-f]{7,40})", version)
        commit = match.group(1) if match else ""
    if not commit:
        checkout = Path("/root/.hermes/hermes-agent")
        commit = run("git", "-C", str(checkout), "rev-parse", "HEAD")
    return version, commit


def git_head() -> str:
    return run("git", "-c", f"safe.directory={REPO_ROOT}", "-C", str(REPO_ROOT),
               "rev-parse", "HEAD")


def write_manifest(path: Path, values: dict[str, str]) -> None:
    version, commit = hermes_identity()
    manifest = {
        "recovery": {
            "schema": "odile.factory-recovery.v1",
            "written_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "hostname": socket.gethostname(),
            "ipv4": detect_ipv4(),
            "hermes_version": version,
            "hermes_commit": commit,
            "git_head": git_head(),
            "zone_id": values["ZONE_ID"],
            "dns_names": values["DNS_NAMES"].split(","),
            "dns_skip": values["DNS_SKIP"].split(","),
            "bucket": BUCKET,
            "endpoint": values["R2_ENDPOINT"],
        }
    }
    path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    path.chmod(0o644)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the Odile factory recovery kit")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--force", action="store_true",
                        help="replace an existing kit folder")
    parser.add_argument("--zone-id", default="",
                        help="32-hex Cloudflare zone id (default: from the state dir)")
    parser.add_argument("--state-dir", type=Path, default=DEFAULT_STATE_DIR,
                        help="where the secrets live (default /root/.odile)")
    args = parser.parse_args()

    for source in (README, RECOVER):
        if not source.is_file():
            raise SystemExit(f"error: missing {source}; run from the repository checkout")

    state: Path = args.state_dir
    zone_id = args.zone_id or read_secret(state / "cloudflare_zone_id",
                                          "the Cloudflare zone id")
    if not re.fullmatch(r"[0-9a-fA-F]{32}", zone_id):
        raise SystemExit("error: the Cloudflare zone id is not 32 hex characters")

    restic_password = read_secret(state / "hq-backup.pass", "the restic passphrase")
    if len(restic_password) != 64:
        raise SystemExit(
            f"error: the restic passphrase is {len(restic_password)} characters, expected 64"
        )
    account_id = read_secret(state / "cloudflare_account_id", "the Cloudflare account id")
    dns_token = read_secret(state / "cloudflare_dns_token", "the Cloudflare DNS token")
    r2 = read_r2(state / "r2-backup.env")

    values = {
        "RESTIC_PASSWORD": restic_password,
        "R2_ACCESS_KEY_ID": r2["AWS_ACCESS_KEY_ID"],
        "R2_SECRET_ACCESS_KEY": r2["AWS_SECRET_ACCESS_KEY"],
        "R2_ENDPOINT": r2["R2_ENDPOINT"].rstrip("/"),
        "CLOUDFLARE_ACCOUNT_ID": account_id,
        "CLOUDFLARE_DNS_TOKEN": dns_token,
        "ZONE_ID": zone_id,
        "DNS_NAMES": ",".join(read_names(DNS_NAMES_FILE, DNS_NAMES)),
        "DNS_SKIP": ",".join(read_names(DNS_SKIP_FILE, DNS_SKIP)),
    }

    out: Path = args.out
    if out.exists():
        if not args.force:
            raise SystemExit(f"error: {out} exists; use --force to replace it")
        if out.is_dir():
            shutil.rmtree(out)
        else:
            out.unlink()
    out.mkdir(parents=True, mode=0o700)
    out.chmod(0o700)

    shutil.copyfile(README, out / "README.md")
    (out / "README.md").chmod(0o644)
    shutil.copyfile(RECOVER, out / "recover.sh")
    (out / "recover.sh").chmod(0o700)
    write_env(out / "recovery.env", values)
    write_manifest(out / "manifest.json", values)

    checksums = [
        f"{sha256(out / name)}  {name}"
        for name in ("README.md", "recover.sh", "recovery.env", "manifest.json")
    ]
    (out / "CHECKSUMS.txt").write_text("\n".join(checksums) + "\n", encoding="utf-8")
    (out / "CHECKSUMS.txt").chmod(0o644)

    # The file set is the contract; a stray file would travel in the kit unseen.
    present = {path.name for path in out.iterdir()}
    if present != set(KIT_FILES):
        raise SystemExit(f"error: kit file set is {sorted(present)}, expected {list(KIT_FILES)}")

    total = sum(path.stat().st_size for path in out.iterdir())
    print(f"Kit written to {out} ({total} bytes, {len(KIT_FILES)} files)")
    print("Store the folder in 1Password and on a USB stick. Do not email it.")
    print("The one-page guide is the kit's README.md; the technical appendix is")
    print("docs/runbooks/backup-hq.md section 5A.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
