#!/usr/bin/python3
"""Embed the first-visit service, its page and the icon set into
installer/odile_install.py.

The installer is one printable, signed file, so the first-visit program, the
page it serves and the five website-icon files travel inside it, pinned by
SHA-256 exactly like `attest.py` and `backup.py`:

    installer/first_visit.py    -> /usr/local/lib/odile/first_visit.py
    web/first-visit.html        -> /usr/local/lib/odile/first-visit.html
    web/favicon.ico             -> /usr/local/lib/odile/icons/favicon.ico
    web/icon-32.png             -> .../icons/icon-32.png
    web/icon-192.png            -> .../icons/icon-192.png
    web/icon-512.png            -> .../icons/icon-512.png
    web/apple-touch-icon.png    -> .../icons/apple-touch-icon.png

The pages are embedded as text; the icons are binary, so they are embedded as
base64 and decoded at install, with each decoded file's SHA-256 checked
against its pin before anything is written.

This tool is the only supported way to refresh those copies, so the embedded
text and the pins can never disagree:

    ./installer/embed_first_visit.py
    ./installer/odile_install.py --self-test   # checks both pins and the sources

After a change here, re-sign the installer (see docs/runbooks/install.md):

    openssl dgst -sign /root/.odile/installer-signing.pem \\
        -out installer/odile_install.py.sig installer/odile_install.py
"""

from __future__ import annotations

import base64
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTALLER = ROOT / "installer" / "odile_install.py"
SERVICE = ROOT / "installer" / "first_visit.py"
PAGE = ROOT / "web" / "first-visit.html"
# The reviewed set, in the order the pages and the tenant route name them.
ICONS = (
    ("favicon.ico", "image/x-icon"),
    ("icon-32.png", "image/png"),
    ("icon-192.png", "image/png"),
    ("icon-512.png", "image/png"),
    ("apple-touch-icon.png", "image/png"),
)

BEGIN = "# BEGIN FIRST VISIT (ODL-457)"
END = "# END FIRST VISIT (ODL-457)"
ICON_BEGIN = "# BEGIN ICON SET (ODL-505)"
ICON_END = "# END ICON SET (ODL-505)"


def read_source(path: Path) -> bytes:
    """Read one source file, refusing bytes the embedded form cannot carry."""
    data = path.read_bytes()
    if b"'''" in data:
        raise SystemExit(f"error: {path} contains a triple single quote")
    try:
        data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise SystemExit(f"error: {path} is not UTF-8: {exc}") from exc
    return data


def read_binary(path: Path) -> bytes:
    """Read one binary source file; empty is a mistake, not a rendition."""
    data = path.read_bytes()
    if not data:
        raise SystemExit(f"error: {path} is empty")
    return data


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def render_block(service: bytes, page: bytes) -> str:
    """The generated region, markers included: the installer's constants."""
    return "\n".join([
        BEGIN,
        "# Generated by installer/embed_first_visit.py; do not edit by hand.",
        "# The first-visit service and its page are the reviewed files, byte for",
        "# byte, so the signed installer carries exactly the program and page it",
        "# writes to /usr/local/lib/odile/. --self-test fails on a one-byte edit.",
        f'FIRST_VISIT_SHA256 = "{digest(service)}"',
        f"FIRST_VISIT_SOURCE = r'''{service.decode('utf-8')}'''",
        f'FIRST_VISIT_PAGE_SHA256 = "{digest(page)}"',
        f"FIRST_VISIT_PAGE = r'''{page.decode('utf-8')}'''",
        END,
    ])


def render_icon_block(icons: list[tuple[str, str, bytes]]) -> str:
    """The icon region: one pinned, base64-encoded entry per reviewed file."""
    lines = [
        ICON_BEGIN,
        "# Generated by installer/embed_first_visit.py; do not edit by hand.",
        "# The five website-icon files under web/ travel inside this signed installer",
        "# as base64, pinned by SHA-256, so a tenant's own page server (and its Webapp",
        "# bundle) carry the reviewed bytes and not a copy fetched from HQ. --self-test",
        "# fails on a one-byte edit.",
        "ICON_SET = (",
    ]
    for name, ctype, data in icons:
        encoded = base64.b64encode(data).decode("ascii")
        lines.append(f'    ("{name}", "{ctype}", "{digest(data)}", "{encoded}"),')
    lines += [")", ICON_END]
    return "\n".join(lines)


def replace_region(text: str, begin: str, end: str, block: str) -> str:
    try:
        start = text.index(begin)
        stop = text.index(end, start) + len(end)
    except ValueError as exc:
        raise SystemExit(f"error: {INSTALLER} has no {begin} markers") from exc
    return text[:start] + block + text[stop:]


def main() -> int:
    service = read_source(SERVICE)
    page = read_source(PAGE)
    icons = [(name, ctype, read_binary(ROOT / "web" / name)) for name, ctype in ICONS]
    text = INSTALLER.read_text(encoding="utf-8")
    text = replace_region(text, BEGIN, END, render_block(service, page))
    text = replace_region(text, ICON_BEGIN, ICON_END, render_icon_block(icons))
    INSTALLER.write_text(text, encoding="utf-8")
    for path, data in ((SERVICE, service), (PAGE, page)):
        print(f"embedded {path.relative_to(ROOT).as_posix()} ({len(data)} bytes, "
              f"sha256 {digest(data)})")
    for name, ctype, data in icons:
        print(f"embedded web/{name} ({len(data)} bytes, sha256 {digest(data)}, "
              f"{ctype})")
    print(f"wrote {INSTALLER.relative_to(ROOT).as_posix()} "
          f"({INSTALLER.stat().st_size} bytes)")
    print("next: ./installer/odile_install.py --self-test, then re-sign")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
