#!/usr/bin/python3
"""Embed support/odile_support.py into installer/odile_install.py.

The installer is one printable, signed file, so the reviewed support programs
(ODL-217) travel inside it, pinned by SHA-256 exactly like `backup.py` and the
first-visit service:

    support/odile_support.py -> /usr/local/sbin/odile-support (0755 root)
                             -> /usr/local/bin/odile-diag (a symlink to it)

This tool is the only supported way to refresh that copy, so the embedded text
and the pin can never disagree:

    ./installer/embed_support.py
    ./installer/odile_install.py --self-test   # checks the hash and the source

After a change here, re-sign the installer (see docs/runbooks/install.md).
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTALLER = ROOT / "installer" / "odile_install.py"
SUPPORT = ROOT / "support" / "odile_support.py"

BEGIN = "# BEGIN SUPPORT (ODL-474)"
END = "# END SUPPORT (ODL-474)"


def read_source(path: Path) -> bytes:
    """Read one source file, refusing bytes the embedded form cannot carry."""
    data = path.read_bytes()
    if b"'''" in data:
        raise SystemExit(f"error: {path} contains a triple single quote")
    try:
        data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise SystemExit(f"error: {path} is not UTF-8: {exc}") from exc
    return data


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def render_block(source: bytes) -> str:
    """The generated region, markers included: the installer's constants."""
    return "\n".join([
        BEGIN,
        "# Generated by installer/embed_support.py; do not edit by hand.",
        "# The support programs are the reviewed file, byte for byte, so the",
        "# signed installer carries exactly what it places at /usr/local/sbin/.",
        "# --self-test fails on a one-byte edit.",
        f'SUPPORT_SHA256 = "{digest(source)}"',
        f"SUPPORT_SOURCE = r'''{source.decode('utf-8')}'''",
        END,
    ])


def main() -> int:
    source = read_source(SUPPORT)
    text = INSTALLER.read_text(encoding="utf-8")
    try:
        start = text.index(BEGIN)
        end = text.index(END, start) + len(END)
    except ValueError as exc:
        raise SystemExit(f"error: {INSTALLER} has no support markers") from exc
    block = render_block(source)
    INSTALLER.write_text(text[:start] + block + text[end:], encoding="utf-8")
    print(f"embedded {SUPPORT.relative_to(ROOT).as_posix()} ({len(source)} bytes, "
          f"sha256 {digest(source)})")
    print(f"wrote {INSTALLER.relative_to(ROOT).as_posix()} "
          f"({INSTALLER.stat().st_size} bytes)")
    print("next: ./installer/odile_install.py --self-test, then re-sign")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
