#!/usr/bin/python3
"""Embed the tenant /verify surface into installer/odile_install.py.

The installer is one printable, signed file, so the page the machine serves
and the programs that write, check and audit its records travel inside it,
pinned by SHA-256 exactly like `first_visit.py` and `attest.py`:

    verify/verify.py                -> /usr/local/lib/odile/verify.py
    templates/verify.html           -> /usr/local/lib/odile/verify.html
    installer/access_report.sh      -> /usr/local/lib/odile/access_report.sh
    scripts/verify_and_unlock.sh    -> /usr/local/lib/odile/verify_and_unlock.sh
    scripts/audit.py                -> /usr/local/bin/odile-audit

The page program is the one `odile-verify.service` runs on 127.0.0.1:8098;
Caddy is the public listener at `/verify`. The access reporter and its wrapper
still write `/var/lib/odile/access-report.txt` for the support bundle, and the
handoff audit (ODL-208) is the program a sceptic runs, so the manifest's
`audit_sha256` names it.

This tool is the only supported way to refresh those copies, so the embedded
text and the pins can never disagree:

    ./installer/embed_verify.py
    ./installer/odile_install.py --self-test   # checks every pin and source

After a change here, re-sign the installer (see docs/runbooks/install.md):

    openssl dgst -sign /root/.odile/installer-signing.pem \\
        -out installer/odile_install.py.sig installer/odile_install.py
"""

from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTALLER = ROOT / "installer" / "odile_install.py"
PROGRAM = ROOT / "verify" / "verify.py"
TEMPLATE = ROOT / "templates" / "verify.html"
WRAPPER = ROOT / "installer" / "access_report.sh"
REPORTER = ROOT / "scripts" / "verify_and_unlock.sh"
AUDIT = ROOT / "scripts" / "audit.py"

BEGIN = "# BEGIN VERIFY SURFACE (ODL-473)"
END = "# END VERIFY SURFACE (ODL-473)"


def read_source(path: Path) -> bytes:
    """Read one source file, refusing bytes the embedded form cannot carry."""
    data = path.read_bytes()
    if b"'''" in data:
        raise SystemExit(f"error: {path} contains a triple single quote")
    try:
        data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise SystemExit(f"error: {path} is not UTF-8: {exc}") from exc
    return data


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def render_block(program: bytes, template: bytes, wrapper: bytes, reporter: bytes,
                 audit_script: bytes) -> str:
    """The generated region, markers included: the installer's constants."""
    return "\n".join([
        BEGIN,
        "# Generated by installer/embed_verify.py; do not edit by hand.",
        "# The /verify program and the page template it renders, plus the two",
        "# programs that write and read the access report and the handoff",
        "# audit, are the reviewed files, byte for byte, so the signed installer",
        "# carries exactly the surface it writes under /usr/local/. --self-test",
        "# fails on a one-byte edit.",
        f'VERIFY_PROGRAM_SHA256 = "{digest(program)}"',
        f"VERIFY_PROGRAM = r'''{program.decode('utf-8')}'''",
        f'VERIFY_TEMPLATE_SHA256 = "{digest(template)}"',
        f"VERIFY_TEMPLATE = r'''{template.decode('utf-8')}'''",
        f'ACCESS_REPORT_SCRIPT_SHA256 = "{digest(wrapper)}"',
        f"ACCESS_REPORT_SCRIPT = r'''{wrapper.decode('utf-8')}'''",
        f'VERIFY_UNLOCK_SHA256 = "{digest(reporter)}"',
        f"VERIFY_UNLOCK = r'''{reporter.decode('utf-8')}'''",
        f'AUDIT_SCRIPT_SHA256 = "{digest(audit_script)}"',
        f"AUDIT_SCRIPT = r'''{audit_script.decode('utf-8')}'''",
        END,
    ])


def main() -> int:
    program = read_source(PROGRAM)
    template = read_source(TEMPLATE)
    wrapper = read_source(WRAPPER)
    reporter = read_source(REPORTER)
    audit_script = read_source(AUDIT)
    text = INSTALLER.read_text(encoding="utf-8")
    try:
        start = text.index(BEGIN)
        end = text.index(END, start) + len(END)
    except ValueError as exc:
        raise SystemExit(f"error: {INSTALLER} has no verify-surface markers") from exc
    block = render_block(program, template, wrapper, reporter, audit_script)
    INSTALLER.write_text(text[:start] + block + text[end:], encoding="utf-8")
    for path, data in ((PROGRAM, program), (TEMPLATE, template), (WRAPPER, wrapper),
                       (REPORTER, reporter), (AUDIT, audit_script)):
        print(f"embedded {path.relative_to(ROOT).as_posix()} ({len(data)} bytes, "
              f"sha256 {digest(data)})")
    print(f"wrote {INSTALLER.relative_to(ROOT).as_posix()} "
          f"({INSTALLER.stat().st_size} bytes)")
    print("next: ./installer/odile_install.py --self-test, then re-sign")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
