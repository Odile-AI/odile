#!/usr/bin/python3
"""Embed the guest export program into installer/odile_install.py.

`odilectl/offboard.py` owns `EXPORT_PROGRAM`: the bytes `odilectl export
<slug> --script` prints and the tenant runs as `odile-export` to take its
home, memory, skills and sessions with it. The installer is one printable,
signed file, so the reviewed program travels inside it, pinned by SHA-256, and
`ensure_export_program` writes exactly those bytes to
``/usr/local/bin/odile-export`` (0755 root).

This tool is the only supported way to refresh that copy, so the embedded text
and the pin can never disagree:

    ./installer/embed_export.py
    ./installer/odile_install.py --self-test   # checks the hash and the source

After a change here, re-sign the installer (see docs/runbooks/install.md §7)
and re-cut the release (`docs/runbooks/install.md` §7, `tools/recut_release.py`).
"""

from __future__ import annotations

import ast
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTALLER = ROOT / "installer" / "odile_install.py"
OFFBOARD = ROOT / "odilectl" / "offboard.py"

BEGIN = "# BEGIN EXPORT PROGRAM (ODL-218 follow-up)"
END = "# END EXPORT PROGRAM (ODL-218 follow-up)"


def export_program(path: Path = OFFBOARD) -> bytes:
    """Read `EXPORT_PROGRAM` from its owner, without importing the CLI.

    The value is the same object `odilectl export <slug> --script` prints; the
    AST read keeps this tool to one source file and one attribute.
    """
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in tree.body:
        if (isinstance(node, ast.Assign)
                and any(isinstance(target, ast.Name) and target.id == "EXPORT_PROGRAM"
                        for target in node.targets)):
            value = ast.literal_eval(node.value)
            if not isinstance(value, str) or not value:
                raise SystemExit(f"error: {path}: EXPORT_PROGRAM is not a non-empty string")
            data = value.encode("utf-8")
            if b"'''" in data:
                raise SystemExit(f"error: {path}: EXPORT_PROGRAM contains a triple single quote")
            return data
    raise SystemExit(f"error: {path} has no EXPORT_PROGRAM assignment")


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def render_block(source: bytes) -> str:
    """The generated region, markers included: the installer's constants."""
    return "\n".join([
        BEGIN,
        "# Generated by installer/embed_export.py; do not edit by hand.",
        "# The guest program is odilectl/offboard.py's EXPORT_PROGRAM, byte for",
        "# byte, so the signed installer places exactly what",
        "# `odilectl export <slug> --script` prints. --self-test fails on a",
        "# one-byte edit.",
        f'EXPORT_PROGRAM_SHA256 = "{digest(source)}"',
        f"EXPORT_PROGRAM_SOURCE = r'''{source.decode('utf-8')}'''",
        END,
    ])


def main() -> int:
    source = export_program()
    text = INSTALLER.read_text(encoding="utf-8")
    try:
        start = text.index(BEGIN)
        end = text.index(END, start) + len(END)
    except ValueError as exc:
        raise SystemExit(f"error: {INSTALLER} has no export-program markers") from exc
    block = render_block(source)
    INSTALLER.write_text(text[:start] + block + text[end:], encoding="utf-8")
    print(f"embedded {OFFBOARD.relative_to(ROOT).as_posix()} EXPORT_PROGRAM "
          f"({len(source)} bytes, sha256 {digest(source)})")
    print(f"wrote {INSTALLER.relative_to(ROOT).as_posix()} "
          f"({INSTALLER.stat().st_size} bytes)")
    print("next: ./installer/odile_install.py --self-test, then re-sign")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
